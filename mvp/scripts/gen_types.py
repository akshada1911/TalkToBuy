"""Generate Pydantic and TypeScript types from mvp/contracts/*.schema.json (T013).

Usage:
    uv run python scripts/gen_types.py           # write generated files
    uv run python scripts/gen_types.py --check   # fail if generated files are stale
"""

from __future__ import annotations

import argparse
import filecmp
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent  # mvp/
CONTRACTS = ROOT / "contracts"

PY_TARGETS = {
    "domain.schema.json": [
        ROOT / "services/session-server/src/session_server/models/domain.py",
        ROOT / "services/demo-store/src/demo_store/models/domain.py",
    ],
    "widget-messages.schema.json": [
        ROOT / "services/session-server/src/session_server/models/messages.py",
    ],
}
TS_TARGETS = {
    "domain.schema.json": ROOT / "packages/assistant-widget/src/types/domain.generated.ts",
    "widget-messages.schema.json": ROOT
    / "packages/assistant-widget/src/types/messages.generated.ts",
}

HEADER = "# GENERATED by scripts/gen_types.py from mvp/contracts/{name}. DO NOT EDIT.\n"


def _run(cmd: list[str]) -> None:
    result = subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True, shell=sys.platform == "win32")
    if result.returncode != 0:
        sys.stderr.write(result.stdout + result.stderr)
        raise SystemExit(f"command failed: {' '.join(cmd)}")


def gen_python(schema: str, out: Path) -> None:
    out.parent.mkdir(parents=True, exist_ok=True)
    _run(
        [
            sys.executable, "-m", "datamodel_code_generator",
            "--input", str(CONTRACTS / schema),
            "--input-file-type", "jsonschema",
            "--output", str(out),
            "--output-model-type", "pydantic_v2.BaseModel",
            "--target-python-version", "3.12",
            "--use-standard-collections",
            "--use-union-operator",
            "--use-schema-description",
            "--enum-field-as-literal", "all",
            "--collapse-root-models",
            "--disable-timestamp",
        ]
    )
    out.write_text(HEADER.format(name=schema) + out.read_text(encoding="utf-8"), encoding="utf-8")
    (out.parent / "__init__.py").touch()


def gen_ts(schema: str, out: Path) -> None:
    out.parent.mkdir(parents=True, exist_ok=True)
    _run(["npx", "--no-install", "json2ts", "-i", str(CONTRACTS / schema), "-o", str(out),
          "--no-additionalProperties", "--bannerComment",
          f"/* GENERATED by scripts/gen_types.py from mvp/contracts/{schema}. DO NOT EDIT. */"])


def generate(redirect: Path | None = None) -> list[tuple[Path, Path]]:
    """Generate all targets. If redirect is given, write there and return (real, temp) pairs."""
    pairs: list[tuple[Path, Path]] = []
    for schema, outs in PY_TARGETS.items():
        for out in outs:
            target = redirect / out.relative_to(ROOT) if redirect else out
            gen_python(schema, target)
            pairs.append((out, target))
    for schema, out in TS_TARGETS.items():
        target = redirect / out.relative_to(ROOT) if redirect else out
        gen_ts(schema, target)
        pairs.append((out, target))
    return pairs


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if not args.check:
        for real, _ in generate():
            print(f"wrote {real.relative_to(ROOT)}")
        return 0
    tmp = Path(tempfile.mkdtemp(prefix="ttb-gen-"))
    try:
        stale = [real for real, new in generate(tmp)
                 if not real.exists() or not filecmp.cmp(real, new, shallow=False)]
    finally:
        shutil.rmtree(tmp, ignore_errors=True)
    if stale:
        print("Generated types are stale; run gen-types:", *[f"  {p.relative_to(ROOT)}" for p in stale], sep="\n")
        return 1
    print("generated types are up to date")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
